static mut VESA_FRAMEBUFFER: *mut u32 = 0 as *mut u32;
static mut VESA_PITCH: u16 = 0;
static mut VESA_WIDTH: u16 = 0;
static mut VESA_HEIGHT: u16 = 0;
static mut VESA_BPP: u8 = 0;

pub fn vesa_init() -> bool {
    let mut controller_info: VbeControllerInfo = unsafe { core::mem::zeroed() };
    
    // Вызов VBE BIOS (int 0x10, ax=0x4f00)
    let ret = vbe_call(
        VBE_FUNCTION_GET_CONTROLLER_INFO,
        VBE_GET_CONTROLLER_INFO,
        &mut controller_info as *mut _ as u32,
    );
    
    // ОТЛАДКА: если vbe_call не вернул 0x004f — VBE не поддерживается
    if ret != 0x004f {
        return false;
    }
    
    // Проверяем поддержку LFB (Linear Frame Buffer)
    if (controller_info.caps & (1 << 16)) == 0 {
        return false;
    }
    
    // Получаем информацию о режиме 1280x800x32
    let mut mode_info: VbeModeInfo = unsafe { core::mem::zeroed() };
    let ret = vbe_call(
        VBE_FUNCTION_GET_MODE_INFO,
        VESA_MODE_1280x800x32,
        &mut mode_info as *mut _ as u32,
    );
    
    if ret != 0x004f {
        return false;
    }
    
    // Проверяем что режим поддерживает LFB (бит 14 = 0x4000)
    if (mode_info.attrs & (0x4000u16)) == 0 {
        return false;
    }
    
    // Сохраняем информацию о режиме
    unsafe {
        VESA_FRAMEBUFFER = mode_info.linear_phys_addr as *mut u32;
        VESA_PITCH = mode_info.pitch;
        VESA_WIDTH = mode_info.width;
        VESA_HEIGHT = mode_info.height;
        VESA_BPP = mode_info.bpp;
        VESA_MODE_INFO = mode_info;
    }
    
    // Устанавливаем режим
    let ret = vbe_call(
        VBE_FUNCTION_SET_MODE,
        VESA_MODE_1280x800x32,
        0,
    );
    
    if ret != 0x004f {
        return false;
    }
    
    true
}

/// Устанавливает framebuffer, полученный от Limine (не через VBE BIOS).
/// Заполняет те же глобальные static'ы, которые используют vesa_draw_char
/// и vesa_print_str — переиспользуем существующий код рисования и шрифт.
/// pitch/width/height передаются как u32 (из Limine они u64).
pub fn vesa_set_framebuffer(addr: *mut u32, pitch: u32, width: u32, height: u32) {
    unsafe {
        VESA_FRAMEBUFFER = addr;
        VESA_PITCH = pitch as u16;
        VESA_WIDTH = width as u16;
        VESA_HEIGHT = height as u16;
    }
}

/// Прокрутка экрана на одну строку шрифта (FONT_HEIGHT пикселей) вверх.
/// Копируем строки пикселей со сдвигом и очищаем нижнюю полосу чёрным.
/// Без прокрутки VESA_TEXT_Y уходил бы за границу экрана (текст обрезался).
fn vesa_scroll_screen() {
    unsafe {
        let width = VESA_WIDTH as usize;
        let height = VESA_HEIGHT as usize;
        let pitch = VESA_PITCH as usize / 4; // pitch в байтах → в u32
        if width == 0 || height == 0 {
            return;
        }
        // Построчно сдвигаем содержимое вверх на FONT_HEIGHT пикселей.
        // Копируем построчно (с учётом pitch), а не сплошным блоком —
        // чтобы не захватывать padding между строками при pitch > width.
        for y in 0..(height - FONT_HEIGHT) {
            let src = VESA_FRAMEBUFFER.offset(((y + FONT_HEIGHT) * pitch) as isize);
            let dst = VESA_FRAMEBUFFER.offset((y * pitch) as isize);
            core::ptr::copy(src, dst, width);
        }
        // Очищаем освободившуюся нижнюю полосу (FONT_HEIGHT строк)
        let last = VESA_FRAMEBUFFER.offset(((height - FONT_HEIGHT) * pitch) as isize);
        core::ptr::write_bytes(last, 0, width * FONT_HEIGHT);
    }
}

#[allow(dead_code)]
pub fn vesa_put_pixel(x: u32, y: u32, color: u32) {
    unsafe {
        if x >= VESA_WIDTH as u32 || y >= VESA_HEIGHT as u32 {
            return;
        }
        
        let offset = (y * VESA_PITCH as u32 / 4) + x;
        *VESA_FRAMEBUFFER.offset(offset as isize) = color;
    }
}

#[allow(dead_code)]
pub fn vesa_get_width() -> u16 {
    unsafe { VESA_WIDTH }
}

#[allow(dead_code)]
pub fn vesa_get_height() -> u16 {
    unsafe { VESA_HEIGHT }
}

fn vbe_call(function: u8, mode: u16, buffer: u32) -> u16 {
    let ax: u16 = ((function as u16) << 8) | 0x4f;
    
    unsafe {
        let mut bx_val: u16 = mode;
        core::arch::asm!(
            "int $0x10",
            in("ax") ax,
            in("edi") bx_val,
            in("ecx") buffer,
            lateout("edi") bx_val,
            options(nostack)
        );
        
        bx_val
    }
}

