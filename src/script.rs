//! Встроенный скриптовый движок Rhai (no_std) для ядра Malinka.
//!
//! Это НОВЫЙ КОД (бирюзовый, правило .kodaruls п.6).
//!
//! Позволяет выполнять скрипты Rhai прямо в ядре (ring 0) — без
//! загрузки ELF и перехода в ring 3. Полезно для:
//!   - автоматизации тестов ядра
//!   - скриптов конфигурации
//!   - демонстрации возможностей в shell (команда `script`)
//!
//! Вывод скриптов (print) направляется в наш print! (VGA+serial+FB).
//! Скрипт может общаться с ядром через зарегистрированные в API
//! функции/переменные (см. register_kernel_api).
//!
//! ВАЖНО: Rhai в этом режиме компилируется с no_std и использует
//! кучи (alloc). Куча у нас есть (allocator.rs, 8 МБ). Скрипты
//! выполняются на kernel-стеке, поэтому длинные рекурсии/циклы
//! ограничивайте — иначе возможен overflow стека (16 КБ).

use rhai::Engine;

/// Выполняет скрипт Rhai из строки. Результат печатается в stdout.
/// При ошибке парсинга/выполнения печатается диагностика.
pub fn run_script(source: &str) {
    // Создаём движок (без модулей/продвинутых функций — минимум для
    // встраивания; можно расширять при необходимости).
    let mut engine = Engine::new();

    // ВАЖНО: НЕ переопределяем print/println через register_fn для одного
    // типа (например String) — Rhai вызовет только подходящую сигнатуру,
    // а print(40+2) передаст целое, print("text") — строку и т.д.
    // Правильный механизм — callback on_print/on_debug, который Rhai
    // вызывает для ВСЕХ типов. В no_std по умолчанию on_print — no-op,
    // поэтому перехватываем и направляем в наш print!.
    engine.on_print(|s: &str| {
        // Rhai передаёт текст БЕЗ перевода строки — добавляем \n,
        // иначе вывод сливается с промптом shell на одной строке.
        crate::println!("{}", s);
    });
    engine.on_debug(|s: &str, _src: Option<&str>, _pos: rhai::Position| {
        crate::println!("[debug] {}", s);
    });

    // Выполняем скрипт. Результат последнего выражения печатаем.
    match engine.eval::<rhai::Dynamic>(source) {
        Ok(value) => {
            // Dynamic не всегда можно Display; печатаем только если
            // значение не пустое.
            if !value.is_unit() {
                crate::println!("=> {}", value.type_name());
            }
        }
        Err(e) => {
            crate::println!("Rhai error: {}", e);
        }
    }
}