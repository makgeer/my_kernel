//! Аллокатор кучи для ядра.
//!
//! Основа для концепции «ядро отдельно, софт отдельно»: без аллокатора
//! невозможно загрузить внешние ELF-программы (нужно выделять память под
//! сегменты, структуры процессов, syscall-буферы и т.д.).
//!
//! Реализация: linked_list_allocator (классический free-list аллокатор,
//! используется в blog_os). Куча — статический массив 8 МБ в секции BSS
//! (higher-half адрес гарантирован линкер-скриптом). Позже, при переходе
//! на нормальный менеджер физической памяти, кучу можно перенести на
//! отдельные страницы, а интерфейс (init_heap + #[global_allocator])
//! останется прежним.

use linked_list_allocator::LockedHeap;
use crate::println;

/// Размер кучи — 8 МБ. Достаточно для загрузки небольших ELF-программ
/// и структур ядра. Увеличится, когда появятся пользовательские процессы.
pub const HEAP_SIZE: usize = 8 * 1024 * 1024;

/// Глобальный аллокатор. Инициализируется через init_heap().
/// `LockedHeap` — потокобезопасная обёртка (spin-лок) вокруг Heap.
#[global_allocator]
static ALLOCATOR: LockedHeap = LockedHeap::empty();

/// Буфер кучи. `static mut` — потому что инициализируем кучей один раз
/// при старте, до создания каких-либо ссылок. Компилятор не может
/// доказать безопасность записи в статик, поэтому unsafe + обоснование.
static mut HEAP: [u8; HEAP_SIZE] = [0x00; HEAP_SIZE];

/// Инициализация кучи: передаём аллокатору адрес и размер буфера.
/// Вызывать ОДИН раз в _start_rust, до первой аллокации.
pub fn init_heap() {
    unsafe {
        ALLOCATOR.lock().init(HEAP.as_mut_ptr(), HEAP_SIZE);
    }
    println!("Heap initialized: {} KiB", HEAP_SIZE / 1024);
}

/// Обработчик ошибок аллокации (обязателен при наличии #[global_allocator]).
#[alloc_error_handler]
fn alloc_error_handler(layout: alloc::alloc::Layout) -> ! {
    panic!("allocation error: {:?}", layout);
}
